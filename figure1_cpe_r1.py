"""Figure 1 of the CPE R1 revision: illustrative constitutional-cycle loss L(T; tau).

Parameters are not chosen here. They are the third draw (record[2]) of the parameter sequence
generated by the submitted script simulation_en.py (np.random.seed(42); 200 draws of
A, B, C ~ 10**U(-1, 1) and alpha, beta ~ U(0.5, 3)), with window duration tau = 1.
T* and the integer optimum are computed, not typed.

Usage:  python3 figure1_cpe_r1.py   (requires numpy, matplotlib)
Outputs: figures_cpe_r1/Fig1.svg, Fig1.eps, Fig1.png (600 dpi), figure1_values.json
"""
import json
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

OUT = Path(__file__).resolve().parent / 'figures_cpe_r1'; OUT.mkdir(exist_ok=True)
plt.rcParams.update({'font.family': 'DejaVu Sans', 'svg.fonttype': 'path', 'ps.fonttype': 42})

np.random.seed(42)
rec = []
for _ in range(200):  # identical draw order to simulation_en.py, part 1
    A_ = 10**np.random.uniform(-1, 1); B_ = 10**np.random.uniform(-1, 1); C_ = 10**np.random.uniform(-1, 1)
    a_ = np.random.uniform(0.5, 3.0); b_ = np.random.uniform(0.5, 3.0)
    rec.append((A_, B_, C_, a_, b_))
A, B, C, alpha, beta = rec[2]
tau = 1.0

def L(T):
    x = np.asarray(T, float) - tau
    return A * x**alpha + B * x**(-beta) + C

x_star = (B * beta / (A * alpha))**(1 / (alpha + beta))
T_star = tau + x_star
lo, hi = int(np.floor(T_star)), int(np.ceil(T_star))
T_int = lo if L(lo) < L(hi) else hi
grid = np.arange(2, 201)
assert int(grid[np.argmin(L(grid))]) == T_int  # integer rule agrees with a grid search

fig, (ax, bx) = plt.subplots(1, 2, figsize=(11, 4.3))
Tc = np.linspace(tau + 0.35, 50, 2000); xc = Tc - tau
ax.plot(Tc, A * xc**alpha, color='tab:orange', ls='--', lw=1.3, label=r'sclerosis term $A(T-\tau)^{\alpha}$')
ax.plot(Tc, B * xc**(-beta), color='tab:purple', ls=':', lw=1.6, label=r'concentrated-authority term $B(T-\tau)^{-\beta}$')
ax.axhline(C, color='grey', lw=0.8, ls='-.', label='baseline cost C')
ax.plot(Tc, L(Tc), color='black', lw=2.0, label=r'total loss $L(T;\tau)$')
Ti = np.arange(2, 51)
ax.plot(Ti, L(Ti), 'o', ms=2.8, color='black', alpha=0.6, label='integer cycle lengths')
ax.axvline(T_star, color='tab:red', ls='--', lw=1.0, label=rf'continuous optimum $T^\ast$ = {T_star:.2f}')
ax.plot([T_int], [L(T_int)], 's', ms=7, mfc='none', mec='tab:green', mew=2, label=f'integer optimum T = {T_int}')
ax.set_xlim(tau, 50); ax.set_ylim(0, 2.6 * L(T_star))
ax.set_xlabel(r'constitutional cycle length $T$ (periods); window duration $\tau$ = 1')
ax.set_ylabel(r'expected loss per period $L(T;\tau)$ (illustrative units)')
ax.set_title('(a) Illustrative loss and its two components', fontsize=10)
ax.legend(fontsize=7.5, loc='upper right', frameon=False)
AA, BB = np.meshgrid(np.linspace(0.05, 6, 400), np.linspace(0.05, 6, 400))
region = ((AA - 1) * (AA - 2) < (BB + 1) * (BB + 2)).astype(float)
bx.contourf(AA, BB, region, levels=[-0.5, 0.5, 1.5], colors=['#f2d7d5', '#d6eaf8'])
bx.contour(AA, BB, (AA - 1) * (AA - 2) - (BB + 1) * (BB + 2), levels=[0], colors='tab:blue', linewidths=1.2)
bx.plot([0, 6], [0, 6], color='black', ls='--', lw=1.0)
bx.plot([alpha], [beta], 'k*', ms=11)
bx.annotate('illustrative\nparameters (a)', (alpha, beta), xytext=(alpha + 0.9, beta + 0.9), fontsize=8,
            arrowprops=dict(arrowstyle='->', lw=0.8))
bx.text(0.5, 5.3, 'shortening by d costs more\nthan lengthening by d (local)', fontsize=8, color='tab:blue')
bx.text(3.9, 0.35, 'lengthening by d\ncosts more (local)', fontsize=8, color='darkred')
bx.text(3.2, 4.1, r'$\alpha=\beta$', fontsize=8, rotation=37)
bx.text(0.35, 3.3, 'above dashed line:\nshortening by a factor k\ncosts more', fontsize=7.5, ha='left')
bx.text(4.1, 1.75, 'below dashed line:\nlengthening by a\nfactor k costs more', fontsize=7.5, ha='left')
bx.set_xlim(0, 6); bx.set_ylim(0, 6)
bx.set_xlabel(r'sclerosis curvature $\alpha$'); bx.set_ylabel(r'concentrated-authority curvature $\beta$')
bx.set_title('(b) Direction of asymmetry depends on parameters', fontsize=10)
fig.tight_layout()
for ext, kw in (('svg', {}), ('eps', {}), ('png', {'dpi': 600})):
    fig.savefig(OUT / f'Fig1.{ext}', **kw)
plt.close(fig)
vals = dict(A=A, B=B, C=C, alpha=alpha, beta=beta, tau=tau, x_star=x_star, T_star=T_star, T_floor=lo, T_ceil=hi,
            L_T_floor=float(L(lo)), L_T_ceil=float(L(hi)), T_int_opt=T_int, L_T_star=float(L(T_star)))
(OUT / 'figure1_values.json').write_text(json.dumps({k: (float(v) if isinstance(v, (float, np.floating)) else int(v)) for k, v in vals.items()}, indent=1))
print(json.dumps({k: round(float(v), 4) for k, v in vals.items()}))
